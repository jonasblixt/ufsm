import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { CodegenError, generateFiles, type UfsmDocument } from "../src";
import { csharpName, csharpOptionsFromTargets, flatten, generateCsharp, lowerToIr } from "../src/pipeline";
import { removeTempDir } from "./c-harness";
import { csproj, dotnetBuild, dotnetEnv, findDotnet, runCsharp } from "./csharp-harness";
import { randomModel } from "./random-model";
import { describeBackend, keywordModel, load, modelFiles, repoRoot } from "./backend-contract";

// The C# tests skip without a .NET SDK; UFSM_REQUIRE_DOTNET=1 (CI) turns that into a failure.
const tools = findDotnet();
if (process.env["UFSM_REQUIRE_DOTNET"] && !tools.dotnet)
  throw new Error(`UFSM_REQUIRE_DOTNET is set but ${tools.problem}`);
const skip = tools.dotnet ? false : (tools.problem ?? "no .NET SDK");
const ir = (doc: UfsmDocument) => lowerToIr(flatten(doc));
const baseName = (f: string): string => f.replace(/^.*[\\/]/, "").replace(/\.ufsm$/, "");
const ns = (f: string): string =>
  baseName(f)
    .replace(/[^A-Za-z0-9_]/g, "_")
    .replace(/^(\d)/, "_$1");

/**
 * Every repo model, the keyword model and some random models in one library, each also with debugInfo and trace. The
 * `<auto-generated/>` marker is removed, so the .NET analyzers (recommended set) check the code too.
 */
function writeRepoLibrary(dir: string): void {
  const docs: [string, UfsmDocument][] = modelFiles.map((f) => [
    `M_${ns(f)}${f.includes("examples") ? "_example" : ""}`,
    load(f),
  ]);
  docs.push(["Keywords", keywordModel()]);
  for (let seed = 1; seed <= 40; seed++)
    docs.push([`Random${seed}`, randomModel(seed, { transitions: 24, signals: seed % 3 })]);
  for (const [space, doc] of docs) {
    for (const [name, lowered, debugInfo] of [
      [space, ir(doc), false],
      [`${space}_debug`, lowerToIr(flatten(doc), { trace: true }), true],
    ] as const) {
      const out = generateCsharp(lowered, { namespace: `Lint.${name}`, file: name, debugInfo });
      writeFileSync(join(dir, out.fileName), out.source.replace("// <auto-generated/>\n", ""));
    }
  }
  writeFileSync(join(dir, "lint.csproj"), csproj(tools.framework!, "Library", true));
}

function docExample(): string {
  const doc = readFileSync(join(repoRoot, "docs/backend-csharp.md"), "utf8");
  const example = /## Example\n\n```csharp\n([\s\S]*?)```/.exec(doc)?.[1];
  assert.ok(example, "docs/backend-csharp.md has an Example section with a csharp block");
  return example;
}

describeBackend({
  name: "C#",
  target: "csharp",
  randomEnv: "UFSM_CSHARP_RANDOM",
  skip,
  run: (units) => runCsharp({ dotnet: tools.dotnet!, framework: tools.framework! }, units),
  timerApi: /void TimerStart\(\w+Timer timer, uint ms, bool periodic\);/,
});

describe("C# backend: generated files", () => {
  it(
    "build without warnings, with XML docs and the recommended analyzers (repo models, random models, debugInfo)",
    { skip },
    async () => {
      const dir = mkdtempSync(join(tmpdir(), "ufsm-cs-"));
      try {
        writeRepoLibrary(dir);
        await dotnetBuild(tools.dotnet!, dir);
      } finally {
        removeTempDir(dir);
      }
    },
  );

  it("run the dimmer example from docs/backend-csharp.md", { skip }, async () => {
    const dir = mkdtempSync(join(tmpdir(), "ufsm-cs-"));
    try {
      const out = generateCsharp(ir(load(join(repoRoot, "examples/dimmer.ufsm"))));
      writeFileSync(join(dir, out.fileName), out.source);
      writeFileSync(join(dir, "Program.cs"), docExample());
      writeFileSync(join(dir, "example.csproj"), csproj(tools.framework!, "Exe"));
      await dotnetBuild(tools.dotnet!, dir);
      const text = execFileSync(tools.dotnet!, [join(dir, "out", "example.dll")], {
        encoding: "utf8",
        env: dotnetEnv(),
      });
      assert.equal(text.trim(), "lamp at 30%");
    } finally {
      removeTempDir(dir);
    }
  });

  it("reject a handler that misses an action", { skip }, () => {
    const dir = mkdtempSync(join(tmpdir(), "ufsm-cs-"));
    try {
      const out = generateCsharp(ir(load(join(repoRoot, "examples/dimmer.ufsm"))));
      writeFileSync(join(dir, out.fileName), out.source);
      writeFileSync(
        join(dir, "Program.cs"),
        "internal sealed class Lamp : IDimmerHandler { public void lamp_off() { } }\n" +
          "internal static class P { private static void Main() { new Dimmer(new Lamp()).Reset(); } }\n",
      );
      writeFileSync(join(dir, "wrong.csproj"), csproj(tools.framework!, "Exe"));
      const r = spawnSync(tools.dotnet!, ["build", "-nologo"], { cwd: dir, encoding: "utf8", env: dotnetEnv() });
      assert.notEqual(r.status, 0);
      assert.match(r.stdout, /CS0535.*IDimmerHandler\.lamp_(10|30|50|100)_percent\(\)/);
    } finally {
      removeTempDir(dir);
    }
  });

  it("keep names as declared, keywords as verbatim identifiers", () => {
    assert.equal(csharpName("event"), "@event");
    assert.equal(csharpName("eButton"), "eButton");
    const out = generateCsharp(ir(load(join(repoRoot, "examples/dimmer.ufsm"))));
    assert.equal(out.fileName, "Dimmer.cs");
    assert.match(out.source, /^\/\/ <auto-generated\/>$/m);
    assert.doesNotMatch(out.source, /^using /m, "no using directives");
    assert.match(out.source, /^public sealed partial class Dimmer$/m);
    assert.match(
      out.source,
      /^public enum DimmerEvent\n\{\n {4}\/\/\/ <summary>Event <c>eButton<\/c>\.<\/summary>\n {4}eButton = 0,$/m,
    );
    assert.match(out.source, /^public interface IDimmerHandler$/m);
    assert.match(out.source, /^ {4}public void Process\(DimmerEvent @event\)$/m);
    const terms = generateCsharp(ir(load(join(repoRoot, "tests/models/test_guard_terms.ufsm")))).source;
    assert.match(terms, /^ {4}not = \d+,$/m, "not is no C# keyword: kept as written");
    const custom = generateCsharp(ir(load(join(repoRoot, "examples/dimmer.ufsm"))), {
      className: "Lamp",
      namespace: "Home.Lights",
      file: "LampFsm",
    });
    assert.equal(custom.fileName, "LampFsm.cs");
    assert.match(custom.source, /^namespace Home\.Lights\n\{$/m);
    assert.match(custom.source, /^ {4}public sealed partial class Lamp$/m);
  });

  it("generate only what the model uses", () => {
    const plain = generateCsharp(ir(load(join(repoRoot, "tests/models/test_guard1.ufsm")))).source;
    assert.doesNotMatch(plain, /queue\[|hist\[|terminated|Settle\(/);
    const signals = generateCsharp(ir(load(join(repoRoot, "tests/models/test_chained_signals.ufsm"))), {
      signalQueue: 5,
    }).source;
    assert.match(signals, /private readonly int\[\] queue = new int\[5\];/);
    assert.match(
      signals,
      /if \(queueLen == 5\)\n\s+\{\n\s+throw new \w+\("queue-overflow"/,
      "the last free slot can be used (B3)",
    );
    const noCheck = generateCsharp(ir(load(join(repoRoot, "tests/models/test_guard1.ufsm"))), {
      maxMicrosteps: 0,
    }).source;
    assert.doesNotMatch(noCheck, /steps|Microstep/);
  });

  it("emit the timer API only for a model with timers", () => {
    const none = generateCsharp(ir(load(join(repoRoot, "tests/models/test_guard1.ufsm"))), { debugInfo: true }).source;
    assert.doesNotMatch(none, /timer/i);
    const src = generateCsharp(ir(load(join(repoRoot, "tests/models/test_timers.ufsm"))), { debugInfo: true }).source;
    assert.match(src, /^public enum TestTimersTimer$/m);
    assert.match(src, /^ {4}public static TestTimersEvent TimerEvent\(TestTimersTimer timer\)$/m);
    assert.match(src, /TimerNames \{ get; \}/);
    assert.match(src, /h\.TimerStart\(TestTimersTimer\.@long, 3600000u, false\);/, "a timer named like a keyword");
  });

  it("reject names that cannot be used in C#", () => {
    const timers = load(join(repoRoot, "tests/models/test_timers.ufsm"));
    timers.declarations.actions[0]!.name = "TimerStart";
    assert.throws(() => generateCsharp(ir(timers)), /action 'TimerStart' is a timer method of the handler/);
    const doc = load(join(repoRoot, "tests/models/test_guard1.ufsm"));
    doc.declarations.actions[0]!.name = "ToString";
    assert.throws(
      () => generateCsharp(ir(doc)),
      (e: unknown) =>
        e instanceof CodegenError && /action 'ToString' is a name every C# object already has/.test(e.message),
    );
    const ok = load(join(repoRoot, "tests/models/test_guard1.ufsm"));
    for (const name of ["class", "9x", "_x"])
      assert.throws(() => generateCsharp(ir(ok), { className: name }), /C# class name/, name);
    assert.throws(() => generateCsharp(ir(ok), { namespace: "A..B" }), /not a usable dotted name/);
    assert.throws(() => generateCsharp(ir(ok), { file: "a/b" }), /not a plain file name/);
  });

  it("read targets.csharp: its own settings, never behaviour options", () => {
    const doc = load(join(repoRoot, "tests/models/test_guard1.ufsm"));
    doc.targets = { csharp: { className: "G", namespace: "Guards", signalQueue: 8, colour: "red", file: 3 } };
    const { options, problems } = csharpOptionsFromTargets(doc);
    assert.deepEqual(options, { className: "G", namespace: "Guards" }, "behaviour options are not read from targets");
    assert.deepEqual(problems, [
      "targets.csharp.signalQueue: changes behaviour, so it is set in options for every target (ignored)",
      "targets.csharp.colour: unknown option (ignored)",
      "targets.csharp.file: expected a string",
    ]);
    const files = generateFiles(doc, "csharp", { className: "Other" });
    assert.equal(files.files[0]!.name, "Other.cs");
    assert.match(files.files[0]!.text, /^ {4}public sealed partial class Other$/m);
  });
});
