/**
 * Licensing: uFSM is GPL-3.0-or-later with an output exception
 * (LICENSE, LICENSE-EXCEPTION). Every source file starts with the SPDX
 * header; generated code says it may be used under any terms and carries
 * no GPL header.
 */
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { OUTPUT_NOTICE, loadModel } from "../src";
import {
  flatten,
  generateC,
  generateCpp,
  generateGo,
  generatePython,
  generateRust,
  generateTypeScript,
  lowerToIr,
} from "../src/pipeline";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const SPDX = "SPDX-License-Identifier: GPL-3.0-or-later";
const SKIP_DIRS = new Set(["node_modules", "old", "build", "target", "dist", ".git", "gen"]);
const CODE = new Set([".ts", ".tsx", ".rs", ".css", ".html", ".yml", ".mjs", ".js"]);

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (!SKIP_DIRS.has(name)) out.push(...sourceFiles(p));
    } else if (CODE.has(extname(name)) || name === "Cargo.toml") out.push(p);
  }
  return out;
}

describe("licensing", () => {
  it("is GPL-3.0-or-later with the output exception", () => {
    assert.match(
      readFileSync(join(repoRoot, "LICENSE"), "utf8"),
      /^\s*GNU GENERAL PUBLIC LICENSE\s+Version 3, 29 June 2007/,
    );
    assert.match(readFileSync(join(repoRoot, "LICENSE-EXCEPTION"), "utf8"), /^uFSM output exception/);
    for (const p of [
      "package.json",
      "packages/core/package.json",
      "packages/cli/package.json",
      "apps/editor/package.json",
    ]) {
      assert.equal(
        (JSON.parse(readFileSync(join(repoRoot, p), "utf8")) as { license?: string }).license,
        "GPL-3.0-or-later",
        p,
      );
    }
    assert.match(
      readFileSync(join(repoRoot, "apps/editor/src-tauri/Cargo.toml"), "utf8"),
      /^license = "GPL-3\.0-or-later"$/m,
    );
  });

  it(
    "keeps the v0.5 code in old/ under its BSD licence",
    { skip: !existsSync(join(repoRoot, "old")) && "old/ not present" },
    () => {
      assert.match(readFileSync(join(repoRoot, "old/LICENSE"), "utf8"), /SPDX-License-Identifier: BSD-3-Clause/);
    },
  );

  it("puts the SPDX header and a copyright line at the top of every source file", () => {
    const files = sourceFiles(repoRoot);
    assert.ok(files.length > 40, `found ${files.length}`);
    const missing = files.filter((f) => {
      const head = readFileSync(f, "utf8").split(/\r?\n/).slice(0, 4).join("\n");
      if (head.startsWith("// Generated by uFSM")) return !head.includes(OUTPUT_NOTICE); // generator output: the exception applies
      return !head.includes(SPDX) || !/Copyright \(C\) \d{4}/.test(head);
    });
    assert.deepEqual(
      missing.map((f) => relative(repoRoot, f)),
      [],
    );
  });

  it("marks generated code as usable under any terms, without a GPL header", () => {
    const ir = lowerToIr(flatten(loadModel(readFileSync(join(repoRoot, "examples/dimmer.ufsm"), "utf8")).doc));
    const c = generateC(ir);
    for (const [name, text] of [
      ["dimmer.h", c.header],
      ["dimmer.c", c.source],
      ["dimmer.py", generatePython(ir).source],
      ["dimmer.ts", generateTypeScript(ir).source],
      ["dimmer.rs", generateRust(ir).source],
      ["dimmer.go", generateGo(ir).source],
      ["dimmer.hpp", generateCpp(ir).source],
    ] as const) {
      const head = text.split("\n").slice(0, 3).join("\n");
      assert.ok(head.includes(OUTPUT_NOTICE), `${name}: ${head}`);
      assert.doesNotMatch(text, /SPDX-License-Identifier|GNU General Public/, name);
    }
  });
});
